// Aircraft
struct AirReport {
    std::string name;
    VehicleClass cls;
    // plane
    float toSpeed = -1, toDist = -1, climb = 0, gearUpAlt = -1, topSpeed = 0, stallSpeed = -1, stallLoss = -1, turnRate = 0;
    // heli
    float spool = -1, hoverDrift = -1, hoverAlt = -1, climbRate = 0, maxSpeed = 0, landed = 0, strike = 0;
    double usPerStep = 0;
};

// altitude/vertical speed hold via elevator (planes)
float pitchForVz(Runner& q, float vzTarget, float& integ) {
    float vz = q.s.body.vel.z;
    float e = vzTarget - vz;
    integ = Clamp(integ + e * 0.02f / 120.f * 60.f, -0.6f, 0.6f);
    float pr = q.s.body.angVel.x * q.s.right().x + q.s.body.angVel.y * q.s.right().y;
    return Clamp(0.08f * e + integ - 0.3f * pr, -1.f, 1.f);
}
float rollForBank(Runner& q, float bankTarget) {
    float e = bankTarget - q.roll();
    return Clamp(e * 2.f - dot(q.s.body.angVel, q.s.forward()) * 0.6f, -1.f, 1.f);
}

void testPlane(const VehicleModel& m, AirReport& rep) {
    Runner r;
    // ---- takeoff roll ----
    ScenarioTrace st_to(r, "plane_takeoff");
    r.init(m, vec3(-4500.f, 0.f, 0.f), -kHalfPi);
    vec3 p0 = r.pos();
    float tAir = -1.f;
    r.stepUs = 0;
    r.steps = 0;
    float vRot = 0.f;
    {
        // rotation speed ~1.15x the clean stall speed estimate
        float S = m.wingArea > 0.5f ? m.wingArea : m.mass / 75.f;
        float vs = sqrtf(2.f * m.mass * 9.81f / (1.225f * S * 1.4f));
        vRot = 1.1f * vs;
    }
    r.run(90.f,
          [&](VehicleControls& c, Runner& q) {
              c.throttle = 1.f;
              c.steer = steerTo(q, vec2(q.pos().x + 100.f, 0.f), 1.f);
              if (q.s.forwardSpeed() > vRot) c.pitch = q.pitch() < 0.17f ? 0.7f : 0.2f;
          },
          [&](Runner& q) {
              bool air = true;
              for (int i = 0; i < q.s.wheelCount; i++) air = air && !q.s.wheels[i].contact;
              if (air && tAir < 0.f) {
                  tAir = q.t;
                  rep.toSpeed = q.s.speed();
                  rep.toDist = length(q.pos().xy() - p0.xy());
              }
              if (!air) tAir = -1.f;
              return tAir > 0.f && q.t - tAir > 1.f;
          });
    // ---- climb at full throttle holding ~8 degrees pitch; gear retraction ----
    ScenarioTrace st_climb(r, "plane_climb");
    float vzAcc = 0.f;
    int n = 0;
    float t0 = r.t;
    r.run(40.f,
          [&](VehicleControls& c, Runner& q) {
              c.throttle = 1.f;
              float pe = 0.14f - q.pitch();
              c.pitch = Clamp(pe * 3.f - q.s.body.angVel.x * 0.f, -1.f, 1.f);
              c.roll = rollForBank(q, 0.f);
          },
          [&](Runner& q) {
              if (rep.gearUpAlt < 0.f && q.s.gearDown < 0.05f) rep.gearUpAlt = q.s.agl;
              if (q.t - t0 > 20.f) {
                  vzAcc += q.s.body.vel.z;
                  n++;
              }
              return false;
          });
    rep.climb = n ? vzAcc / n : 0.f;
    // ---- turn south (heading hold) and climb to 400 m over land ----
    ScenarioTrace st_nav(r, "plane_nav");
    float integ = 0.f;
    const float hdgSouth = -kHalfPi;
    auto headingBank = [&](Runner& q, float hdg) {
        float e = wrapPi(hdg - q.heading());  // + = target to the left
        return Clamp(-e * 1.2f, -0.5f, 0.5f);
    };
    r.run(240.f,
          [&](VehicleControls& c, Runner& q) {
              c.throttle = 1.f;
              c.roll = rollForBank(q, headingBank(q, hdgSouth));
              c.pitch = pitchForVz(q, (float)q.s.body.pos.z < 400.f ? 3.f : 0.f, integ);
          },
          [&](Runner& q) { return q.s.body.pos.z > 400.0 && fabsf(wrapPi(hdgSouth - q.heading())) < 0.05f; });
    // ---- level top speed (altitude hold) ----
    ScenarioTrace st_top(r, "plane_top");
    float vTop = 0.f;
    float zHold = (float)r.s.body.pos.z;
    r.run(80.f,
          [&](VehicleControls& c, Runner& q) {
              c.throttle = 1.f;
              c.pitch = pitchForVz(q, Clamp((zHold - (float)q.s.body.pos.z) * 0.1f, -5.f, 5.f), integ);
              c.roll = rollForBank(q, headingBank(q, hdgSouth));
          },
          [&](Runner& q) {
              vTop = Max(vTop, q.s.speed());
              return false;
          });
    rep.topSpeed = r.s.speed();
    // ---- coordinated turn without rudder: 30 degree bank ----
    ScenarioTrace st_turnp(r, "plane_turn");
    float hh = r.heading();
    r.run(10.f,
          [&](VehicleControls& c, Runner& q) {
              c.throttle = 1.f;
              c.roll = rollForBank(q, 0.52f);
              c.pitch = pitchForVz(q, 0.f, integ);
          },
          [](Runner&) { return false; });
    rep.turnRate = fabsf(wrapPi(r.heading() - hh)) / 10.f * kRadToDeg;
    // ---- stall: throttle idle, hold altitude until the wing lets go ----
    ScenarioTrace st_stall(r, "plane_stall");
    zHold = (float)r.s.body.pos.z;
    float zStall = 0.f;
    float ts = r.run(120.f,
                     [&](VehicleControls& c, Runner& q) {
                         c.throttle = 0.f;
                         c.pitch = pitchForVz(q, Clamp((zHold - (float)q.s.body.pos.z) * 0.2f, -3.f, 3.f), integ);
                         c.roll = rollForBank(q, headingBank(q, hdgSouth));
                     },
                     [&](Runner& q) {
                         if (q.s.stall > 0.5f || (float)q.s.body.pos.z < zHold - 15.f) {
                             rep.stallSpeed = q.s.speed();
                             zStall = (float)q.s.body.pos.z;
                             return true;
                         }
                         return false;
                     });
    if (ts > 0.f) {
        // recovery: release the stick, full throttle; altitude lost until climbing again
        float zMin = zStall;
        r.run(30.f,
              [&](VehicleControls& c, Runner& q) {
                  c.throttle = 1.f;
                  c.roll = rollForBank(q, 0.f);
                  if (q.s.stall < 0.1f && q.s.speed() > rep.stallSpeed * 1.15f) c.pitch = 0.7f;
              },
              [&](Runner& q) {
                  zMin = Min(zMin, (float)q.s.body.pos.z);
                  return q.s.body.vel.z > 1.f && q.s.stall < 0.1f;
              });
        rep.stallLoss = zStall - zMin;
    }
    rep.usPerStep = r.stepUs / Max(r.steps, 1L);
}

void testHeli(const VehicleModel& m, AirReport& rep) {
    gPG->resetColliders();
    Runner r;
    r.init(m, vec3(-3000.f, 300.f, 0.f), 0.f);
    r.stepUs = 0;
    r.steps = 0;
    // ---- spool-up (engine on, no collective) ----
    ScenarioTrace st_sp(r, "heli_spool");
    rep.spool = r.run(30.f, [](VehicleControls&, Runner&) {}, [](Runner& q) { return q.s.rotorSpeed > 0.98f; });
    // ---- climb at full collective ----
    ScenarioTrace st_cl(r, "heli_climb");
    float vzMax = 0.f;
    r.run(15.f, [](VehicleControls& c, Runner&) { c.lift = 1.f; }, [&](Runner& q) {
        vzMax = Max(vzMax, q.s.body.vel.z);
        return q.s.body.pos.z > 40.0;
    });
    rep.climbRate = vzMax;
    // ---- hover: zero input for 3 s to settle, then 10 s drift ----
    ScenarioTrace st_hv(r, "heli_hover");
    r.run(3.f, [](VehicleControls&, Runner&) {}, [](Runner&) { return false; });
    vec3 p0 = r.pos();
    float maxD = 0.f;
    r.run(10.f, [](VehicleControls&, Runner&) {}, [&](Runner& q) {
        maxD = Max(maxD, length(q.pos() - p0));
        return false;
    });
    rep.hoverDrift = maxD;
    rep.hoverAlt = r.s.agl;
    // ---- max speed: full forward cyclic with altitude hold ----
    ScenarioTrace st_mx(r, "heli_speed");
    float zHold = (float)r.s.body.pos.z, vTop = 0.f;
    r.run(40.f,
          [&](VehicleControls& c, Runner& q) {
              c.pitch = -1.f;
              c.lift = Clamp(((zHold - (float)q.s.body.pos.z) * 0.3f - q.s.body.vel.z * 0.5f), -1.f, 1.f);
          },
          [&](Runner& q) {
              vTop = Max(vTop, sqrtf(Sq(q.s.body.vel.x) + Sq(q.s.body.vel.y)));
              return false;
          });
    rep.maxSpeed = vTop;
    // ---- stop, descend and land ----
    ScenarioTrace st_ld(r, "heli_land");
    r.run(15.f, [](VehicleControls&, Runner&) {}, [](Runner&) { return false; });
    float tl = r.run(40.f, [](VehicleControls& c, Runner&) { c.lift = -0.6f; }, [](Runner& q) { return q.s.agl < 0.3f && q.s.speed() < 0.2f; });
    r.run(3.f, [](VehicleControls&, Runner&) {}, [](Runner&) { return false; });
    rep.landed = (tl > 0.f && r.s.up().z > 0.95f) ? 1.f : 0.f;
    rep.usPerStep = r.stepUs / Max(r.steps, 1L);
    // ---- rotor strike: hover next to the tower and drift into it ----
    ScenarioTrace st_rs(r, "heli_strike");
    r.init(m, vec3(-2000.f, 370.f, 0.f), 0.f);
    r.s.rotorSpeed = 1.f;
    r.run(6.f, [](VehicleControls& c, Runner& q) { c.lift = q.s.body.pos.z < 25.0 ? 1.f : 0.f; }, [](Runner&) { return false; });
    bool hit = false;
    r.run(15.f, [](VehicleControls& c, Runner&) { c.pitch = -0.5f; }, [&](Runner& q) {
        hit = hit || q.s.rotorStrike;
        return hit;
    });
    rep.strike = hit ? 1.f : 0.f;
}

