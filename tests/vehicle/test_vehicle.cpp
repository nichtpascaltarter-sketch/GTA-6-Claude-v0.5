void issue(const char* fmt, ...) {
    char buf[1024];
    va_list ap;
    va_start(ap, fmt);
    vsnprintf(buf, sizeof(buf), fmt, ap);
    va_end(ap);
    gIssues.push_back(buf);
}

const vec3 kPadStart(-4800.f, 0.f, 0.f);

