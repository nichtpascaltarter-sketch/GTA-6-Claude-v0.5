struct BoatReport {
    std::string name;
    VehicleClass cls;
    float t50 = -1, topSpeed = 0, humpPitch = 0, humpSpeed = 0, planeSpeed = -1, turnDiam = -1, turnRoll = 0;
    float heaveIdle = 0, pitchIdle = 0, rollIdle = 0, heaveRun = 0, pitchRun = 0;
    float beachStop = -1, beachUpright = 0, mudSpeed = -1, drift = 0, capsized = 0;
    double usPerStep = 0;
};

void testBoat(const VehicleModel& m, BoatReport& rep) {
    Runner r;
    Phys::gWaves.strength = 0.3f;
    Phys::gWaves.time = 0.f;
    // ---- acceleration, planing, top speed ----
    ScenarioTrace st_acc(r, "boat_accel");
    r.init(m, vec3(3700.f, -1000.f, 0.f), -kHalfPi);
    float vTop = 0.f, pMax = 0.f, pMaxV = 0.f;
    bool planed = false;
    r.stepUs = 0;
    r.steps = 0;
    r.run(70.f,
          [&](VehicleControls& c, Runner& q) {
              c.throttle = 1.f;
              c.steer = steerTo(q, vec2(q.pos().x + 50.f, -1000.f), 1.f);
              Phys::gWaves.time = q.t;
          },
          [&](Runner& q) {
              float v = q.s.forwardSpeed();
              if (rep.t50 < 0.f && v > 13.9f) rep.t50 = q.t;
              vTop = Max(vTop, v);
              float p = q.pitch() * kRadToDeg;
              if (p > pMax) {
                  pMax = p;
                  pMaxV = v;
              }
              if (!planed && pMax > 2.f && p < pMax * 0.5f && v > pMaxV) {
                  planed = true;
                  rep.planeSpeed = v;
              }
              return q.pos().x > 6300.f;
          });
    rep.usPerStep = r.stepUs / Max(r.steps, 1L);
    rep.topSpeed = vTop;
    rep.humpPitch = pMax;
    rep.humpSpeed = pMaxV;
    // ---- turning circle at full throttle, full right ----
    ScenarioTrace st_turn(r, "boat_turn");
    r.init(m, vec3(5000.f, 0.f, 0.f), -kHalfPi);
    r.run(15.f, [&](VehicleControls& c, Runner& q) { c.throttle = 1.f; Phys::gWaves.time = q.t; }, [](Runner&) { return false; });
    float h0 = r.heading();
    vec2 mn(1e9f), mx(-1e9f);
    float turned = 0.f, lastH = h0, rollAcc = 0.f;
    int rn = 0;
    r.run(60.f,
          [&](VehicleControls& c, Runner& q) {
              c.throttle = 1.f;
              c.steer = 1.f;
              Phys::gWaves.time = q.t;
          },
          [&](Runner& q) {
              float h = q.heading();
              turned += fabsf(wrapPi(h - lastH));
              lastH = h;
              if (turned > kPi) {
                  mn = vmin(mn, q.pos().xy());
                  mx = vmax(mx, q.pos().xy());
                  rollAcc += q.roll();
                  rn++;
              }
              if (q.s.up().z < 0.3f) rep.capsized = 1.f;
              return turned > 3.f * kPi;
          });
    rep.turnDiam = 0.5f * ((mx.x - mn.x) + (mx.y - mn.y));
    rep.turnRoll = rn ? rollAcc / rn * kRadToDeg : 0.f;
    // ---- wave riding: strong waves, idle then 15 m/s ----
    ScenarioTrace st_wave(r, "boat_waves");
    Phys::gWaves.strength = 1.0f;
    r.init(m, vec3(5000.f, -500.f, 0.f), 0.f);
    auto stats = [&](float dur, float speed, float& heave, float& pitch, float& roll) {
        double sz = 0, szz = 0, sp = 0, spp = 0, sr = 0, srr = 0;
        int n = 0;
        float t0 = r.t;
        r.run(dur,
              [&](VehicleControls& c, Runner& q) {
                  if (speed > 0.f) holdSpeed(c, q, speed);
                  Phys::gWaves.time = q.t;
              },
              [&](Runner& q) {
                  if (q.t - t0 < 5.f) return false;
                  float z = (float)q.s.body.pos.z, p = q.pitch(), rr = q.roll();
                  sz += z; szz += z * z; sp += p; spp += p * p; sr += rr; srr += rr * rr;
                  n++;
                  return false;
              });
        heave = (float)sqrt(Max(szz / n - Sq(sz / n), 0.0));
        pitch = (float)sqrt(Max(spp / n - Sq(sp / n), 0.0)) * kRadToDeg;
        roll = (float)sqrt(Max(srr / n - Sq(sr / n), 0.0)) * kRadToDeg;
    };
    stats(25.f, 0.f, rep.heaveIdle, rep.pitchIdle, rep.rollIdle);
    float dummy;
    stats(25.f, 15.f, rep.heaveRun, rep.pitchRun, dummy);
    Phys::gWaves.strength = 0.3f;
    // ---- beaching: 10 m/s toward the west shore ----
    ScenarioTrace st_beach(r, "boat_beach");
    r.init(m, vec3(3350.f, 800.f, 0.f), kHalfPi);  // heading -x toward the beach at x ~ 3100
    float tb = r.run(40.f,
                     [&](VehicleControls& c, Runner& q) {
                         if (q.pos().x > 3120.f) holdSpeed(c, q, 10.f);
                         Phys::gWaves.time = q.t;
                     },
                     [&](Runner& q) { return q.pos().x < 3140.f && q.s.speed() < 0.3f; });
    rep.beachStop = tb;
    rep.beachUpright = r.s.up().z;
    // ---- airboat: lake -> shallow mud water -> dry mud ----
    if (m.cls == VC_AIRBOAT) {
        ScenarioTrace st_mud(r, "boat_mud");
        r.init(m, vec3(4000.f, 1400.f, 0.f), 0.f);  // heading +y
        float vAcc = 0.f;
        int n = 0;
        r.run(90.f,
              [&](VehicleControls& c, Runner& q) {
                  c.throttle = 1.f;
                  c.steer = steerTo(q, vec2(4000.f, q.pos().y + 40.f), 1.f);
                  Phys::gWaves.time = q.t;
              },
              [&](Runner& q) {
                  if (q.pos().y > 2750.f && q.pos().y < 3300.f) {
                      vAcc += q.s.speed();
                      n++;
                  }
                  return q.pos().y > 3300.f;
              });
        rep.mudSpeed = n ? vAcc / n : 0.f;
    }
    // ---- drift with no input (wind/waves) ----
    Phys::gWaves.strength = 0.3f;
}

