// Real world: long random drives on the generated road graph with streamed collision, building + curb checks
void testReal(RealWorld& rw, const VehicleModel& m, RealReport& rep, u32 seed, float routeLen) {
    Rng rng(seed);
    Route route;
    bool bike = m.cls == VC_MOTORBIKE || m.cls == VC_SCOOTER;
    route.build(rw.roads, rng, routeLen, true);
    if (route.pts.size() < 3 || route.totalLen < 300.f) return;
    Runner r;
    ScenarioTrace st(r, "real_drive");
    vec3 p0 = route.pts[0];
    vec2 d0 = normalize(route.pts[2].xy() - p0.xy());
    auto yawOf = [](vec2 d) { return atan2f(-d.x, d.y); };  // yaw 0 = +Y, positive CCW
    rw.ensureCells(p0.xy());
    r.init(m, p0 + vec3(0, 0, 0.3f), yawOf(d0));
    int idx = 0;
    float sNow = 0.f, stuckT = 0.f, driven = 0.f, bridgeDist = 0.f, tDrive = 0.f, lastSupportZ = -1e9f;
    vec3 lastP = r.pos();
    r.stepUs = 0;
    r.steps = 0;
    int stepCount = 0;
    auto respawnAhead = [&](float ahead) {
        float s2 = Min(sNow + ahead, route.totalLen - 1.f);
        vec3 p = route.at(s2);
        vec2 d = normalize(route.at(s2 + 3.f).xy() - p.xy());
        rw.ensureCells(p.xy());
        resetVehicle(r.s, dvec3(p + vec3(0, 0, 0.3f)), yawOf(d));
        idx = route.advance(p.xy(), idx);
        sNow = s2;
        lastP = r.pos();
    };
    float tMax = routeLen / 8.f + 60.f;
    r.run(tMax,
          [&](VehicleControls& c, Runner& q) {
              if (++stepCount % 60 == 0) rw.ensureCells(q.pos().xy());
              idx = route.advance(q.pos().xy(), idx);
              sNow = route.dist[idx];
              float v = q.s.speed();
              float look = 6.f + 0.45f * v;
              vec3 tgt = route.at(sNow + look);
              c.steer = steerTo(q, tgt.xy(), 1.6f);
              float lim = route.limit[idx] * 1.15f;
              float aLat = bike ? 4.5f : 5.5f;
              float vc = route.cornerSpeed(sNow, 20.f + v * 3.f, aLat);
              float vT = Min(Min(lim, vc), m.topSpeed * 0.85f);
              // still turning onto the new heading: the pure-pursuit arc to the look-ahead point bounds the speed
              {
                  vec2 dT = tgt.xy() - q.pos().xy();
                  float L = length(dT);
                  vec3 f = q.s.forward();
                  vec2 f2 = normalize(vec2(f.x, f.y) + vec2(1e-6f, 0.f));
                  float sa = L > 1e-3f ? fabsf(cross(f2, dT / L)) : 0.f;
                  if (sa > 0.05f) vT = Min(vT, Max(sqrtf(aLat * L / (2.f * sa)), 3.f));
              }
              holdSpeed(c, q, vT);
          },
          [&](Runner& q) {
              vec3 p = q.pos();
              float step = length(p.xy() - lastP.xy());
              lastP = p;
              if (step < 5.f) driven += step;
              if (route.bridge[idx]) bridgeDist += step;
              tDrive += 1.f / 120.f;
              rep.maxRoll = Max(rep.maxRoll, fabsf(q.roll()) * kRadToDeg);
              if (fabsf(q.pitch()) * kRadToDeg > 25.f && rep.maxPitch * kDegToRad < fabsf(q.pitch()))
                  printf("EVENT pitch %.0f deg at (%.1f %.1f %.1f) v=%.1f s=%.0f bridge=%d\n", q.pitch() * kRadToDeg, p.x, p.y, p.z, q.s.speed(), sNow, (int)route.bridge[idx]);
              rep.maxPitch = Max(rep.maxPitch, fabsf(q.pitch()) * kRadToDeg);
              if (q.s.impactImpulse > 5000.f && q.s.impactCollider >= 0) rep.impacts++;
              rep.broken += q.s.brokenCount;
              if (!std::isfinite(p.x)) {
                  rep.nans++;
                  respawnAhead(30.f);
                  return false;
              }
              // genuine fall-through: the surface that supported the car last step is now well above it
              {
                  Phys::GroundHit gNow = Phys::gCollision->ground(p.x, p.y, lastSupportZ + 0.3f, 0.f);
                  bool deckAbove = gNow.z > p.z + 1.0f && fabsf(gNow.z - lastSupportZ) < 0.3f;
                  if (deckAbove) {
                      printf("EVENT fell-through at (%.1f %.1f %.1f) surface %.1f v=%.1f vz=%.1f s=%.0f\n", p.x, p.y, p.z, gNow.z, q.s.speed(), q.s.body.vel.z, sNow);
                      rep.fellThrough++;
                      respawnAhead(40.f);
                      lastSupportZ = -1e9f;
                      return false;
                  }
                  Phys::GroundHit gBelow = Phys::gCollision->ground(p.x, p.y, p.z + 0.5f, 0.f);
                  lastSupportZ = q.s.wheelsOnGround > 0 ? gBelow.z : -1e9f;
              }
              // left an elevated road over an unguarded edge (world geometry), counted separately
              if (route.bridge[idx] && p.z < route.pts[idx].z - 2.5f) {
                  printf("EVENT off-deck at (%.1f %.1f %.1f) deck %.1f v=%.1f s=%.0f\n", p.x, p.y, p.z, route.pts[idx].z, q.s.speed(), sNow);
                  rep.offDeck++;
                  respawnAhead(40.f);
                  return false;
              }
              if (q.s.up().z < 0.3f && !bike) {
                  printf("EVENT flip at (%.1f %.1f %.1f) v=%.1f s=%.0f bridge=%d\n", p.x, p.y, p.z, q.s.speed(), sNow, (int)route.bridge[idx]);
                  rep.flips++;
                  respawnAhead(30.f);
                  return false;
              }
              if (bike && q.s.riderOff) {
                  printf("EVENT bike crash at (%.1f %.1f %.1f) v=%.1f lean=%.0f pitch=%.0f impact=%.0f/%d s=%.0f bridge=%d\n", p.x, p.y, p.z, q.s.speed(), q.s.lean * kRadToDeg,
                         q.pitch() * kRadToDeg, q.s.impactImpulse, q.s.impactCollider, sNow, (int)route.bridge[idx]);
                  rep.flips++;
                  respawnAhead(30.f);
                  return false;
              }
              stuckT = q.s.speed() < 0.5f ? stuckT + 1.f / 120.f : 0.f;
              if (stuckT > 4.f) {
                  // is the lane itself blocked by a world collider (building/garage/tree on the road)?
                  bool blocked = false;
                  {
                      std::vector<int> ids;
                      rw.cw.collidersNear(p.xy(), 8.f, ids);
                      for (int id : ids) {
                          const Phys::Collider& c = rw.cw.collider(id);
                          if (c.owner < 0 || c.he.x <= 0.f) continue;
                          for (float ahead = 0.f; ahead <= 8.f && !blocked; ahead += 1.f) {
                              vec3 lp = route.at(sNow + ahead);
                              vec2 dd = lp.xy() - c.c.xy();
                              if (c.kind == Phys::COL_BOX) {
                                  vec2 ay(-c.ax.y, c.ax.x);
                                  if (fabsf(dot(dd, c.ax)) < c.he.x + 0.8f && fabsf(dot(dd, ay)) < c.he.y + 0.8f && lp.z + 0.5f > c.c.z - c.he.z) blocked = true;
                              } else if (length(dd) < c.he.x + 0.8f) {
                                  blocked = true;
                              }
                          }
                      }
                  }
                  printf("EVENT stuck%s at (%.1f %.1f %.1f) route (%.1f %.1f %.1f) s=%.0f bridge=%d up=%.2f\n", blocked ? "(lane blocked by world collider)" : "", p.x, p.y, p.z,
                         route.pts[idx].x, route.pts[idx].y, route.pts[idx].z, sNow, (int)route.bridge[idx], q.s.up().z);
                  if (blocked) rep.blocked++;
                  else rep.stuck++;
                  stuckT = 0.f;
                  respawnAhead(30.f);
                  return false;
              }
              return sNow > route.totalLen - 30.f;
          });
    rep.km += driven / 1000.f;
    rep.bridgeKm += bridgeDist / 1000.f;
    rep.avgSpeed = tDrive > 0.f ? driven / tDrive : 0.f;
    rep.usPerStep = r.stepUs / Max(r.steps, 1L);
}

// Aim at a real building from 45 m at 60 km/h: must stop at the wall, not pass through.
void testRealBuilding(RealWorld& rw, const VehicleModel& m, RealReport& rep, u32 seed) {
    Rng rng(seed);
    for (int tries = 0; tries < 20000; tries++) {
        const World::Building& b = rw.bs.buildings[rng.next() % rw.bs.buildings.size()];
        if (b.height < 6.f || b.hx < 6.f) continue;
        vec2 start = b.c + b.front * (b.hy + 45.f);
        float rz;
        if (!rw.roads.surfaceHeight(start, &rz, 1e9f)) continue;
        // clear path (no other building between start and the facade)
        bool clear = true;
        for (float t = 0.f; t < 38.f; t += 2.f) {
            vec2 q = start - b.front * t;
            float top;
            if (rw.bs.pointInBuilding(q, 1.5f, &top)) clear = false;
        }
        if (!clear) continue;
        if (fabsf(rz - b.baseZ) > 1.5f) continue;
        rw.ensureCells(start);
        rw.ensureCells(b.c);
        // the approach must be drivable: no drops or steps on the way, and the first thing hit must be the building itself
        bool flat = true;
        float prevZ = rz;
        for (float t = 2.f; t < 44.f && flat; t += 2.f) {
            vec2 q = start - b.front * t;
            Phys::GroundHit g = rw.cw.ground(q.x, q.y, prevZ + 1.f, 0.f);
            if (fabsf(g.z - prevZ) > 0.3f || g.water) flat = false;
            prevZ = g.z;
        }
        if (!flat) continue;
        Phys::RayHit rh;
        vec3 ro(start, rz + 0.7f), rd(-b.front, 0.f);
        if (!rw.cw.raycast(ro, rd, 60.f, rh, false) || rh.collider < 0 || !(rw.cw.collider(rh.collider).flags & 2)) continue;
        Runner r;
        ScenarioTrace st(r, "real_building");
        vec2 d = -b.front;
        r.init(m, vec3(start, rz + 0.3f), atan2f(-d.x, d.y));
        float minSpeedAfter = 1e9f;
        bool hit = false;
        float tHit = 0.f;
        r.run(12.f,
              [&](VehicleControls& c, Runner& q) {
                  if (!hit) holdSpeed(c, q, 16.7f);
                  c.steer = hit ? 0.f : steerTo(q, b.c, 1.5f);
              },
              [&](Runner& q) {
                  if (!hit && q.s.impactImpulse > 3.f * m.mass && q.s.impactCollider >= 0 && rw.cw.collider(q.s.impactCollider).flags & 2) {
                      hit = true;
                      tHit = q.t;
                  }
                  if (hit) minSpeedAfter = Min(minSpeedAfter, q.s.speed());
                  return hit && q.t - tHit > 2.f;
              });
        rep.bldgStop = hit ? minSpeedAfter : -1.f;
        rep.bldgInside = rw.bs.pointInBuilding(r.pos().xy(), -0.5f) ? 1.f : 0.f;
        rep.bldgHealth = r.s.health;
        return;
    }
}

// Cross a real street with sidewalks at walking pace (curb up/down twice).
void testRealCurb(RealWorld& rw, const VehicleModel& m, RealReport& rep, u32 seed) {
    Rng rng(seed);
    for (int tries = 0; tries < 2000; tries++) {
        const World::RoadEdge& e = rw.roads.edges[rng.next() % rw.roads.edges.size()];
        if (e.sidewalk < 1.f || e.cls != World::RC_STREET || e.length < 60.f || (e.flags & (World::RF_BRIDGE | World::RF_ELEVATED))) continue;
        float sMid = e.length * 0.5f;
        vec3 c = e.posAt(sMid);
        vec3 tng = e.tangentAt(sMid);
        vec2 n(tng.y, -tng.x);
        float reach = e.halfWidth + e.sidewalk;
        vec2 a = c.xy() - n * (reach + 4.f), bpt = c.xy() + n * (reach + 4.f);
        bool clear = true;
        for (float t = 0.f; t <= 1.f; t += 0.05f)
            if (rw.bs.pointInBuilding(lerp(a, bpt, t), 3.f)) clear = false;
        if (!clear) continue;
        // no other road/intersection nearby (keep it a plain mid-block crossing)
        int ne = rw.roads.nearestEdge(a, 3.f);
        if (ne >= 0 && &rw.roads.edges[ne] != &e) continue;
        rw.ensureCells(c.xy());
        // keep the crossing line free of street furniture (a light pole stops a car at walking pace, as it should)
        bool furnitureFree = true;
        for (float lo = -1.5f; lo <= 1.51f && furnitureFree; lo += 0.25f) {
            vec2 side(-n.y, n.x);
            vec2 a2 = a + side * lo;
            float gz0 = rw.map.heightAt(a2.x, a2.y);
            Phys::RayHit rh;
            vec3 ro(a2, Max(gz0, c.z) + 0.5f), rd(n, 0.f);
            if (rw.cw.raycast(ro, rd, 2.f * (reach + 4.f) + 10.f, rh, false) && rh.collider >= 0) furnitureFree = false;
        }
        if (!furnitureFree) continue;
        Runner r;
        ScenarioTrace st(r, "real_curb");
        float gz = rw.map.heightAt(a.x, a.y);
        r.init(m, vec3(a, Max(gz, c.z) + 0.2f), atan2f(-n.x, n.y));
        float tc = r.run(25.f,
                         [&](VehicleControls& cc, Runner& q) {
                             holdSpeed(cc, q, 3.f);
                             cc.steer = steerTo(q, bpt + n * 10.f, 1.5f);
                         },
                         [&](Runner& q) { return dot(q.pos().xy() - c.xy(), n) > reach + 2.f; });
        rep.curbCrossed = tc;
        return;
    }
}

