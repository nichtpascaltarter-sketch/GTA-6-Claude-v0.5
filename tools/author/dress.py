def edge_side_dist(e, x, y):
    """Distance from the centreline, its s, and the side (+1 left of travel, -1 right)."""
    best = (1e30, 0.0, 1)
    for k in range(len(e["pts"]) - 1):
        (ax, ay), (bx, by) = e["pts"][k], e["pts"][k + 1]
        dx, dy = bx - ax, by - ay
        L2 = max(dx * dx + dy * dy, 1e-9)
        t = min(max(((x - ax) * dx + (y - ay) * dy) / L2, 0.0), 1.0)
        qx, qy = ax + t * dx, ay + t * dy
        d = math.hypot(x - qx, y - qy)
        if d < best[0]:
            side = 1 if dx * (y - ay) - dy * (x - ax) > 0 else -1
            best = (d, e["s"][k] + t * math.sqrt(L2), side)
    return best


# A parcel is levelled (grade=) a kerb's step under the sidewalks along it. Ungraded, its ground lay 0.45 m under them
# where the roads' grading cuts the terrain (roadgrade.cpp): a knee-high step down into every yard. Its ground lies
# 0.03 m over the grade (worldc), so the step is 0.17 m at the lowest sidewalk along it, and more where its sidewalks
# climb: a parcel whose sidewalks climb more than YARD_RISE along it isn't levelled (one level wouldn't meet them all;
# the promenade's strips are cut into terraces instead), and the report names it.
KERB = 0.15        # a sidewalk's top over its road's centreline height (roadnet.cpp roadSurfaceHeight)
YARD_STEP = 0.20   # the grade under the lowest sidewalk along the parcel
YARD_RISE = 0.15


def edges_near(poly):
    xs, ys = [q[0] for q in poly], [q[1] for q in poly]
    near = []
    for e in edges:
        r = max(e["hwL"], e["hwR"]) + max(e["swL"], e["swR"]) + 2.0
        ex, ey = [q[0] for q in e["pts"]], [q[1] for q in e["pts"]]
        if min(ex) - r <= max(xs) and max(ex) + r >= min(xs) and min(ey) - r <= max(ys) and max(ey) + r >= min(ys):
            near.append(e)
    return near


def sidewalks_along(poly):
    """The sidewalk tops along a parcel's outline: at every metre of its sides that runs along a street's sidewalk (the
    sidewalk's outer edge within a metre), the street's height there plus the kerb."""
    near = edges_near(poly)
    zs = []
    n = len(poly)
    for k in range(n):
        (ax, ay), (bx, by) = poly[k], poly[(k + 1) % n]
        m = max(1, int(math.hypot(bx - ax, by - ay)))
        for j in range(m):
            f = (j + 0.5) / m
            x, y = ax + (bx - ax) * f, ay + (by - ay) * f
            for e in near:
                d, s, side = edge_side_dist(e, x, y)
                if abs(d - (hw_on(e, side) + sw_on(e, side))) < 1.0 and 0.0 < s < e["plen"]:
                    zs.append((zat(e, s) + KERB, e["name"]))
    return zs


# A levelled parcel's outline runs on UNDER metres under the streets along it: the block's outline comes from a 0.5 m
# raster, simplified to 0.45 m, and left gaps of up to a metre between a levelled yard and the street's skirt, down to
# the terrain the roads' grading cut. Each vertex within REACH of a street's edge (its sidewalk's outer edge, else its
# carriageway's) moves out to UNDER under it, where the street there is higher than the yard (the street's skirt hides
# the yard's edge). A vertex by two streets with sidewalks, at a junction, moves under both, as if both had the
# narrower one: the junction's corner is drawn that wide (roadmesh.cpp), and the wider sidewalk stops at its cut-back.
UNDER = 0.5
REACH = 1.3


def with_tees(poly, others):
    """The outline with every vertex of the block's other parcels that lies on one of its sides added there, so that
    the two still meet along it when their vertices move (run_under). (Not its own: one within 2 cm of its next side
    would come back as a spike there, which the ground's triangulation can't take.)"""
    own = set(poly)
    out = []
    n = len(poly)
    for k in range(n):
        a, b = poly[k], poly[(k + 1) % n]
        out.append(a)
        dx, dy = b[0] - a[0], b[1] - a[1]
        L2 = dx * dx + dy * dy
        if L2 < 0.0025:
            continue
        on = []
        for v in others:
            if v in own:
                continue
            f = ((v[0] - a[0]) * dx + (v[1] - a[1]) * dy) / L2
            if 0.0 < f < 1.0 and abs(dx * (a[1] - v[1]) - (a[0] - v[0]) * dy) / math.sqrt(L2) < 0.02:
                on.append((f, v))
        out += [v for f, v in sorted(on)]
    return out


def run_under(poly, yard):
    near = edges_near(poly)
    out = []
    for (x, y) in poly:
        by = []
        for e in near:
            d, s, side = edge_side_dist(e, x, y)
            if not (0.5 < s < e["plen"] - 0.5):
                continue   # (beyond its ends the junction's or the next edge's)
            sw = sw_on(e, side)
            reach = hw_on(e, side) + sw
            if not (reach - UNDER < d < reach + REACH) or zat(e, s) + (KERB if sw > 0.0 else 0.0) < yard + 0.02:
                continue
            by.append((e, d, s, side, sw))
        walks = [b for b in by if b[4] > 0.0]
        narrow = min(b[4] for b in walks) if len(walks) >= 2 else None
        lines = []   # each street's line UNDER under its edge: a point on it and its direction
        for e, d, s, side, sw in by:
            target = hw_on(e, side) + (min(sw, narrow) if narrow is not None and sw > 0.0 else sw) - UNDER
            (qx, qy), (tx, ty) = at(e, s)
            nx, ny = (x - qx) / d, (y - qy) / d
            lines.append(((qx + nx * target, qy + ny * target), (tx, ty)))
        q = (x, y)
        if len(lines) == 1:
            (px, py), (tx, ty) = lines[0]
            f = (x - px) * tx + (y - py) * ty
            q = (px + tx * f, py + ty * f)
        elif len(lines) >= 2:   # (where two meet, at a junction: the corner of the two)
            (p1x, p1y), (t1x, t1y) = lines[0]
            (p2x, p2y), (t2x, t2y) = lines[1]
            den = t1x * t2y - t1y * t2x
            if abs(den) > 0.2:
                f = ((p2x - p1x) * t2y - (p2y - p1y) * t2x) / den
                q = (p1x + t1x * f, p1y + t1y * f)
        q = (round(q[0], 2), round(q[1], 2))
        if not out or q != out[-1]:
            out.append(q)
    while len(out) > 1 and out[0] == out[-1]:
        out.pop()
    return out


def grade_of(poly, front):
    """A parcel's grade, or None (no sidewalk along it, or one level won't meet them all), and its sidewalks' range. A
    sidewalk along it more than 0.1 m over its front street's (a ramp climbing past its end) doesn't count: the yard
    stands under it as under a wall."""
    zs = sidewalks_along(poly)
    cap = max([z for z, name in zs if name == front], default=None)
    zs = [z for z, name in zs if cap is None or z <= cap + 0.1]
    if not zs:
        return None, None
    lo, hi = min(zs), max(zs)
    return (round(lo - YARD_STEP, 2) if hi - lo <= YARD_RISE else None), (lo, hi)


def chain(e):
    """The edges of e's street joined end to end (the same name, meeting at a node with no turn sharper than 30 degrees),
    as one polyline in e's direction: a frontage that runs on past a junction (Calle Luna's jog at Avenida Palma)."""
    if e["name"] in ("", None):
        return e
    pts = list(e["pts"])
    for forward in (True, False):
        cur = e
        while True:
            end = cur["n1"] if forward else cur["n0"]
            tip, prev = (pts[-1], pts[-2]) if forward else (pts[0], pts[1])
            dx, dy = tip[0] - prev[0], tip[1] - prev[1]
            nxt = None
            for o in edges:
                if o is cur or o["name"] != e["name"] or end not in (o["n0"], o["n1"]):
                    continue
                op = o["pts"] if o["n0"] == end else o["pts"][::-1]   # from the shared node outward
                ex, ey = op[1][0] - op[0][0], op[1][1] - op[0][1]
                c = (dx * ex + dy * ey) / max(math.hypot(dx, dy) * math.hypot(ex, ey), 1e-9)
                if c > math.cos(math.radians(30)):
                    nxt = (o, op)
                    break
            if not nxt or len(pts) > 400:
                break
            o, op = nxt
            pts = pts + op[1:] if forward else op[::-1][:-1] + pts
            cur = o
            # (the chain's far node, for the next step)
            cur = dict(o)
            cur["n0"], cur["n1"] = (end, o["n1"] if o["n0"] == end else o["n0"]) if forward else (o["n1"] if o["n0"] == end else o["n0"], end)
    c = dict(e)
    c["pts"] = pts
    ss = [0.0]
    for a, b in zip(pts, pts[1:]):
        ss.append(ss[-1] + math.hypot(b[0] - a[0], b[1] - a[1]))
    c["s"], c["plen"] = ss, ss[-1]
    return c


def frontages(poly):
    """The streets along a polygon's sides: per edge, the length of outline it borders, and which side faces the block."""
    out = {}
    n = len(poly)
    for k in range(n):
        (ax, ay), (bx, by) = poly[k], poly[(k + 1) % n]
        L = math.hypot(bx - ax, by - ay)
        if L < 0.5:
            continue
        mx, my = (ax + bx) / 2, (ay + by) / 2
        for e in edges:
            d, s, side = edge_side_dist(e, mx, my)
            if abs(d - (hw_on(e, side) + sw_on(e, side))) < 1.5:
                o = out.setdefault(e["id"], {"edge": e, "len": 0.0, "side": side, "dir": None, "best": 0.0})
                o["len"] += L
                if L > o["best"]:
                    o["best"], o["dir"] = L, ((bx - ax) / L, (by - ay) / L)
    return out


def use_of(f):
    name = f["edge"]["name"]
    if name == "Avenida Flores":
        return "commercial"
    if name in SHOP_STREETS or name in MIXED_STREETS or name == "Paseo del Rio":
        return "mixed"
    return "residential"


def score(f):
    e = f["edge"]
    if e["cls"] == RC_LANE or f["len"] < 15.0:
        return 0.0
    w = 2.0 if e["name"] in SHOP_STREETS else 1.5 if e["cls"] in (RC_AVENUE, RC_BOULEVARD) or e["name"] == "Paseo del Rio" else 1.0
    return f["len"] * w


def row_of(half, f, rng, holes):
    """One row of parcels along street f's frontage on `half`: cut at intervals of arc length, each cut along the street's
    normal there, so the lots follow a curved street; the first and last reach round the corners."""
    e, side = chain(f["edge"]), f["side"]
    near = hw_on(e, side) + sw_on(e, side) + 2.5
    ss = []
    for q in half:
        d, sq, sd = edge_side_dist(e, q[0], q[1])
        if d <= near and sd == side:
            ss.append(sq)
    if len(ss) < 2:
        return []
    sa, sb = min(ss), max(ss)
    use = use_of(f)
    lo, hi = (11.0, 16.0) if use == "residential" else (14.0, 22.0)
    cuts = [sa]
    while sb - cuts[-1] > hi + lo * 0.6:
        cuts.append(cuts[-1] + rng.uniform(lo, hi))
    cuts.append(sb)
    # how deep the half reaches from the street; the cuts fan out along a curved street, but never so fast that two cross
    # inside it
    depth = max(edge_side_dist(e, q[0], q[1])[0] for q in half) + 5.0
    L = depth
    dirs = []
    for c in cuts:
        (cx_, cy_), (tx_, ty_) = at(e, c)
        # the street's direction averaged over 10 m either side (one kink doesn't swing a cut)
        (p0, _), (p1, _) = at(e, c - 10.0), at(e, c + 10.0)
        dx, dy = p1[0] - p0[0], p1[1] - p0[1]
        Ld = math.hypot(dx, dy) or 1.0
        dirs.append(math.atan2(dy / Ld, dx / Ld))
    for k in range(1, len(dirs)):
        w = cuts[k] - cuts[k - 1]
        lim = math.atan2(w, L) * 0.8
        dd = (dirs[k] - dirs[k - 1] + math.pi) % (2 * math.pi) - math.pi
        dirs[k] = dirs[k - 1] + max(-lim, min(lim, dd))
    out = []
    for k in range(len(cuts) - 1):
        (ax, ay), _ = at(e, cuts[k])
        (bx, by), _ = at(e, cuts[k + 1])
        atx, aty = math.cos(dirs[k]), math.sin(dirs[k])
        btx, bty = math.cos(dirs[k + 1]), math.sin(dirs[k + 1])
        anx, any_ = -aty * side, atx * side   # toward the block
        bnx, bny = -bty * side, btx * side
        if k == 0:   # round the corner: the first lot reaches back past the block's end
            ax, ay = ax - atx * 40.0, ay - aty * 40.0
        if k == len(cuts) - 2:
            bx, by = bx + btx * 40.0, by + bty * 40.0
        quad = [(ax - anx * 2.0, ay - any_ * 2.0), (bx - bnx * 2.0, by - bny * 2.0), (bx + bnx * L, by + bny * L), (ax + anx * L, ay + any_ * L)]
        if area(quad) < 0:
            quad = quad[::-1]
        p = half
        for j in range(4):   # clip by the quad's four sides (it is convex, counter-clockwise)
            (qx, qy), (rx, ry) = quad[j], quad[(j + 1) % 4]
            nx_, ny_ = ry - qy, -(rx - qx)   # the outward normal of a CCW side
            p = clip(p, nx_, ny_, nx_ * qx + ny_ * qy)
            if len(p) < 3:
                break
        p = dedupe(p)
        if len(p) < 3 or abs(area(p)) < 40.0:
            continue
        mx, my = sum(q[0] for q in p) / len(p), sum(q[1] for q in p) / len(p)
        if any(inside(h, mx, my) for h in holes):
            continue
        out.append({"poly": p, "use": use, "front": f, "u": (atx, aty), "v": (anx, any_)})
    return out


def parcels_of(bid, poly, rng, holes):
    """Cut a block region's polygon into parcels: one row along its main frontage, or, where a street (not an alley)
    runs along its back too, two rows back to back, split halfway."""
    fr = frontages(poly)
    cands = [f for f in fr.values() if score(f) > 0]
    if not cands:
        return []
    main = max(cands, key=score)
    ux, uy = main["dir"]
    cx = sum(p[0] for p in poly) / len(poly)
    cy = sum(p[1] for p in poly) / len(poly)
    d_, s_, side_ = edge_side_dist(main["edge"], cx, cy)
    (px, py), _ = at(main["edge"], s_)
    vx, vy = -uy, ux
    if (cx - px) * vx + (cy - py) * vy < 0:
        vx, vy = -vx, -vy
    us = [p[0] * ux + p[1] * uy for p in poly]
    vs = [p[0] * vx + p[1] * vy for p in poly]
    u0, u1, v0, v1 = min(us), max(us), min(vs), max(vs)
    back = [f for f in cands if f is not main and f["len"] > 0.5 * (u1 - u0) and abs(f["dir"][0] * ux + f["dir"][1] * uy) > 0.8]
    # hand-made parcels at an end of the block: the generated lots stop at them
    for h in holes:
        hu = [q[0] * ux + q[1] * uy for q in h]
        hv = [q[0] * vx + q[1] * vy for q in h]
        if max(hv) < v0 or min(hv) > v1 or max(hu) < u0 or min(hu) > u1:
            continue
        if min(hu) <= u0 + 12.0:
            poly = clip(poly, -ux, -uy, -max(hu))
        elif max(hu) >= u1 - 12.0:
            poly = clip(poly, ux, uy, min(hu))
    if back:
        vm = (v0 + v1) / 2
        halves = [(clip(poly, vx, vy, vm), main), (clip(poly, -vx, -vy, -vm), back[0])]
    else:
        halves = [(poly, main)]
    out = []
    for half, f in halves:
        if len(half) >= 3:
            out += row_of(half, f, rng, holes)
    for o in out:
        o["poly"] = [(round(q[0], 2), round(q[1], 2)) for q in o["poly"]]
    return out


