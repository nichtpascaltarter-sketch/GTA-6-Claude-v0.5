def mark_segment(ax, ay, bx, by, r):
    x0, x1 = min(ax, bx) - r, max(ax, bx) + r
    y0, y1 = min(ay, by) - r, max(ay, by) + r
    i0, i1 = max(int((x0 - X0) / MPP), 0), min(int((x1 - X0) / MPP) + 1, NX)
    j0, j1 = max(int((y0 - Y0) / MPP), 0), min(int((y1 - Y0) / MPP) + 1, NY)
    if i0 >= i1 or j0 >= j1:
        return
    px, py = GX[j0:j1, i0:i1], GY[j0:j1, i0:i1]
    dx, dy = bx - ax, by - ay
    L2 = max(dx * dx + dy * dy, 1e-9)
    t = np.clip(((px - ax) * dx + (py - ay) * dy) / L2, 0, 1)
    d2 = (px - ax - t * dx) ** 2 + (py - ay - t * dy) ** 2
    taken[j0:j1, i0:i1] |= d2 <= r * r


def mark_segment_sides(ax, ay, bx, by, rl, rr):
    """A street segment with its sidewalks, each side to its own reach (rl left of travel, rr right)."""
    r = max(rl, rr)
    x0, x1 = min(ax, bx) - r, max(ax, bx) + r
    y0, y1 = min(ay, by) - r, max(ay, by) + r
    i0, i1 = max(int((x0 - X0) / MPP), 0), min(int((x1 - X0) / MPP) + 1, NX)
    j0, j1 = max(int((y0 - Y0) / MPP), 0), min(int((y1 - Y0) / MPP) + 1, NY)
    if i0 >= i1 or j0 >= j1:
        return
    px, py = GX[j0:j1, i0:i1], GY[j0:j1, i0:i1]
    dx, dy = bx - ax, by - ay
    L2 = max(dx * dx + dy * dy, 1e-9)
    t = np.clip(((px - ax) * dx + (py - ay) * dy) / L2, 0, 1)
    d2 = (px - ax - t * dx) ** 2 + (py - ay - t * dy) ** 2
    left = dx * (py - ay) - dy * (px - ax) > 0
    rs = np.where(left, rl, rr)
    taken[j0:j1, i0:i1] |= d2 <= rs * rs


