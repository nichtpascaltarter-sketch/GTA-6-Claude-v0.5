def yaw_toward(dx, dy):
    """NTW yaw (CCW degrees) turning a piece's +y to (dx, dy)."""
    return (math.degrees(math.atan2(-dx, dy)) + 360.0) % 360.0


def fmt(v, d=2):
    s = ("%." + str(d) + "f") % v
    return "0." + "0" * d if s in ("-0." + "0" * d,) else s


TREES = {"Calle Luna": ("lib.veg.royal_palm", 11.5, 13.5), "Avenida Flores": ("lib.veg.royal_palm", 12.0, 14.0),
         "Paseo de los Heroes": ("lib.veg.royal_palm", 11.0, 13.0), "Bougainvillea Boulevard": ("lib.veg.royal_palm", 12.0, 14.0),
         "Avenida del Sol": ("lib.veg.palm", 7.5, 9.0), "Paseo del Rio": ("lib.veg.palm", 7.0, 9.0)}
DEFAULT_TREE = ("lib.veg.live_oak", 7.0, 9.0)


def dress_sidewalks(bid, polys, rng, avoid):
    """Street trees, lights, hydrants, bins, benches and news boxes on the sidewalks along a block's frontages."""
    out = []
    placed = list(avoid)   # (kind, x, y)

    def free(x, y, r, kinds=None):
        for k, px, py in placed:
            if (kinds is None or k in kinds) and (px - x) ** 2 + (py - y) ** 2 < r * r:
                return False
        return True

    seen = set()
    for poly in polys:
        for fid, f in frontages(poly).items():
            if fid in seen:
                continue
            seen.add(fid)
            e = f["edge"]
            side = f["side"]   # +1: the block is left of travel
            hw, sw = hw_on(e, side), sw_on(e, side)
            if sw < 2.0:
                continue
            shop = e["name"] in SHOP_STREETS
            big = e["cls"] in (RC_AVENUE, RC_BOULEVARD)
            s0, s1 = e["cut0"] + 5.0, e["plen"] - e["cut1"] - 5.0
            if s1 - s0 < 8.0:
                continue

            def spot(s, off):
                (px, py), (tx_, ty_) = at(e, s)
                lx, ly = -ty_ * side, tx_ * side   # toward the block
                return px + lx * off, py + ly * off, (lx, ly)

            # (only the stretch along this block: the part of the sidewalk whose building side touches the polygon)
            def ours(s):
                x, y, (lx, ly) = spot(s, hw + sw + 1.0)
                return any(inside(p, x, y) for p in polys)

            # street lights: avenues and boulevards every 30 m, streets every 34 m; the arm over the road
            step = 30.0 if big else 34.0
            phase = rng.uniform(0.3, 0.7) * step
            s = s0 + phase * 0.5
            while s <= s1:
                if ours(s):
                    x, y, (lx, ly) = spot(s, hw + 0.7)
                    if free(x, y, 8.0, {"light"}) and free(x, y, 2.0):
                        out.append(("light", "lib.light.street_cobra", x, y, yaw_toward(-lx, -ly), {}))
                        placed.append(("light", x, y))
                s += step
            # street trees between the lights, on sidewalks of 3.5 m or more
            if sw >= 3.5:
                tree, h0, h1 = TREES.get(e["name"], DEFAULT_TREE)
                tstep = 15.0 if shop else 17.0
                s = s0 + rng.uniform(2.0, 6.0)
                while s <= s1:
                    if ours(s):
                        x, y, _ = spot(s, hw + 1.2)
                        if free(x, y, 4.0) and free(x, y, 6.0, {"light"}):
                            out.append(("tree", tree, x, y, None, {"h": rng.uniform(h0, h1)}))
                            placed.append(("tree", x, y))
                    s += tstep
            # a hydrant near one end of each stretch
            for s in (s0 + 1.0, s1 - 1.0):
                if ours(s):
                    x, y, (lx, ly) = spot(s, hw + 0.6)
                    if free(x, y, 30.0, {"prop.hydrant"}) and free(x, y, 2.0):
                        out.append(("prop", "lib.prop.hydrant", x, y, None, {}))
                        placed.append(("prop.hydrant", x, y))
                        break
            # shopping streets: bins at both ends, a bench and a news box at the building side, parking meters
            if shop or big:
                for s in (s0 + 3.0, s1 - 3.0):
                    if ours(s):
                        x, y, (lx, ly) = spot(s, hw + 0.9)
                        if free(x, y, 2.5):
                            out.append(("prop", "lib.prop.trash_bin", x, y, None, {}))
                            placed.append(("prop.bin", x, y))
                sm = (s0 + s1) / 2
                if ours(sm):
                    x, y, (lx, ly) = spot(sm, hw + sw - 0.7)
                    if free(x, y, 3.0):
                        out.append(("prop", "lib.prop.bench", x, y, yaw_toward(-lx, -ly), {}))
                        placed.append(("prop.bench", x, y))
            if shop:
                if ours(s0 + 6.0):
                    x, y, (lx, ly) = spot(s0 + 6.0, hw + sw - 0.6)
                    if free(x, y, 2.0):
                        out.append(("prop", "lib.prop.news_box", x, y, yaw_toward(-lx, -ly), {}))
                        placed.append(("prop.news", x, y))
                s = s0 + 9.0
                while s <= s1 - 6.0:
                    if ours(s):
                        x, y, (lx, ly) = spot(s, hw + 0.45)
                        if free(x, y, 2.5):
                            out.append(("prop", "lib.prop.parking_meter", x, y, yaw_toward(lx, ly), {}))
                            placed.append(("prop.meter", x, y))
                    s += 14.0
    return out


def dress_parcel(p, rng):
    """A parcel's ground and paint, and its yard's trees and shrubs."""
    recs = []
    poly = p["poly"]
    ux, uy = p["u"]
    vx, vy = p["v"]   # into the parcel from its street
    us = [q[0] * ux + q[1] * uy for q in poly]
    vs = [q[0] * vx + q[1] * vy for q in poly]
    u0, u1, v0, v1 = min(us), max(us), min(vs), max(vs)

    def xy(u, v):   # (u along the street, v away from it) to plan x, y
        return (u * ux + v * vx, u * uy + v * vy)

    if p["use"] == "residential":
        paint = []
        # a driveway on one side, 3 m wide and 9 m deep
        side = rng.random() < 0.5
        da, db = (u0 + 0.8, u0 + 3.8) if side else (u1 - 3.8, u1 - 0.8)
        if u1 - u0 > 9.0 and v1 - v0 > 12.0:
            paint.append(("paving", [xy(da, v0), xy(db, v0), xy(db, v0 + 9.0), xy(da, v0 + 9.0)]))
        recs.append(("parcel_ground", "lawn", paint))
        # a tree or two in the back yard, shrubs by the front
        for k in range(rng.choice((1, 1, 2))):
            u = rng.uniform(u0 + 3.0, u1 - 3.0)
            v = rng.uniform(v0 + (v1 - v0) * 0.7, v1 - 3.0)
            kind = rng.choice(("lib.veg.live_oak", "lib.veg.palm", "lib.veg.live_oak", "lib.veg.street_tree"))
            h = {"lib.veg.live_oak": (6.0, 8.5), "lib.veg.palm": (6.5, 8.5), "lib.veg.street_tree": (5.0, 6.5)}[kind]
            x, y = xy(u, v)
            recs.append(("tree", kind, x, y, None, {"h": rng.uniform(*h)}))
        for k in range(rng.choice((1, 2, 2, 3))):
            u = rng.uniform(u0 + 1.5, u1 - 1.5)
            if da - 1.0 < u < db + 1.0:
                continue
            x, y = xy(u, v0 + rng.uniform(1.2, 2.5))
            recs.append(("plant", "lib.veg.shrub", x, y, None, {"scale": rng.uniform(0.8, 1.2)}))
    else:
        recs.append(("parcel_ground", "paving", []))
    return recs


