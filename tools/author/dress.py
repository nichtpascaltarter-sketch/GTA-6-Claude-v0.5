def at(e, s):
    """Point and unit tangent at plan distance s along e."""
    pts, ss = e["pts"], e["s"]
    s = min(max(s, 0.0), ss[-1])
    for k in range(len(pts) - 1):
        if s <= ss[k + 1] or k == len(pts) - 2:
            L = max(ss[k + 1] - ss[k], 1e-6)
            f = (s - ss[k]) / L
            ax, ay = pts[k]
            bx, by = pts[k + 1]
            return (ax + (bx - ax) * f, ay + (by - ay) * f), ((bx - ax) / L, (by - ay) / L)
    return pts[-1], (1.0, 0.0)


def zat(e, s):
    """The road's height at plan distance s along e (between its points, as RoadEdge::posAt)."""
    pz, ss = e["pz"], e["s"]
    s = min(max(s, 0.0), ss[-1])
    for k in range(len(ss) - 1):
        if s <= ss[k + 1] or k == len(ss) - 2:
            f = (s - ss[k]) / max(ss[k + 1] - ss[k], 1e-6)
            return pz[k] + (pz[k + 1] - pz[k]) * f
    return pz[-1]


