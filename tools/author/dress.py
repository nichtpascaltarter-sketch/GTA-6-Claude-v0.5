def riverfront():
    """The promenade: a strip along the Paseo del Rio's water side, from its sidewalk to a metre short of the water (at
    most 12 m), in pieces wherever it narrows below 3 m."""
    strips = []
    for e in river:
        cur = []
        s = e["cut0"] + 2.0
        while s <= e["plen"] - e["cut1"] - 2.0:
            (px, py), (tx_, ty_) = at(e, s)
            nx_, ny_ = ty_, -tx_   # (right of travel)
            wside = -1
            if ny_ > 0:   # (toward the water: south)
                nx_, ny_ = -nx_, -ny_
                wside = 1
            d0 = hw_on(e, wside) + sw_on(e, wside)
            w = 0.0
            while w < 13.0:   # (from 0.6 m out: a pixel's centre can be 0.35 m nearer the road than the point sampled)
                x, y = px + nx_ * (d0 + w + 0.6), py + ny_ * (d0 + w + 0.6)
                i, j = int((x - X0) / MPP), int((y - Y0) / MPP)
                if not (0 <= i < NX and 0 <= j < NY) or taken[j, i]:
                    break
                w += 0.5
            w = min(w - 1.0, 12.0)
            if w >= 3.0:
                cur.append(((px + nx_ * d0, py + ny_ * d0), (px + nx_ * (d0 + w), py + ny_ * (d0 + w)), (nx_, ny_), w))
            elif len(cur) >= 3:
                strips.append(cur)
                cur = []
            else:
                cur = []
            s += 4.0
        if len(cur) >= 3:
            strips.append(cur)
    polys = []
    for st in strips:
        poly = [x[0] for x in st] + [x[1] for x in reversed(st)]
        poly = rdp_closed(poly, 0.3)
        polys.append(poly if area(poly) > 0 else poly[::-1])
    RIVER_SAMPLES[:] = strips
    return polys


RIVER_SAMPLES = []


def promenade_terraces(st):
    """A promenade strip cut across where its sidewalk climbs: runs of its samples (every 4 m) along which the sidewalk
    climbs YARD_RISE at most, each run's last sample the next one's first, as polygons."""
    zs = []
    for a, b, n_, w in st:
        best = None
        for e in river:
            d, s, side = edge_side_dist(e, a[0], a[1])
            if best is None or d < best[0]:
                best = (d, zat(e, s) + KERB)
        zs.append(best[1])
    runs, i = [], 0
    while i < len(st) - 1:
        j, lo, hi = i + 1, min(zs[i], zs[i + 1]), max(zs[i], zs[i + 1])
        while j + 1 < len(st) and max(hi, zs[j + 1]) - min(lo, zs[j + 1]) <= YARD_RISE - 0.03:
            j += 1
            lo, hi = min(lo, zs[j]), max(hi, zs[j])
        runs.append(st[i:j + 1])
        i = j
    out = []
    for run in runs:
        poly = rdp_closed([x[0] for x in run] + [x[1] for x in reversed(run)], 0.3)
        out.append(poly if area(poly) > 0 else poly[::-1])
    return out


def dress_riverfront(rng):
    """The promenade's palms down its middle, benches at the water's edge facing the water, and bollards with garden
    lamps along it."""
    out = []
    for st in RIVER_SAMPLES:
        for k, (a, b, (nx_, ny_), w) in enumerate(st):
            mx, my = (a[0] + b[0]) / 2, (a[1] + b[1]) / 2
            if k % 4 == 2:   # every 16 m
                out.append(("tree", "lib.veg.palm", mx, my, None, {"h": rng.uniform(6.5, 8.5)}))
            if k % 8 == 6 and w >= 4.0:   # every 32 m, between the palms
                x, y = b[0] - nx_ * 1.2, b[1] - ny_ * 1.2
                out.append(("prop", "lib.prop.bench", x, y, yaw_toward(nx_, ny_), {}))
            if k % 3 == 0:   # every 12 m
                x, y = b[0] - nx_ * 0.4, b[1] - ny_ * 0.4
                out.append(("prop", "lib.prop.bollard", x, y, None, {}))
                out.append(("light", "lib.light.garden", x, y, None, {"z": 0.95}))
            if k % 8 == 2 and w >= 4.0:
                x, y = b[0] - nx_ * 1.0, b[1] - ny_ * 1.0
                out.append(("prop", "lib.prop.trash_bin", x + 2.0 * ny_, y - 2.0 * nx_, None, {}))
    return out


