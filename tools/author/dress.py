def hand_part(bid):
    path = os.path.join(WORLD, "districts/cl/blocks", bid, "block.ntw")
    if not os.path.exists(path):
        return None
    text = open(path).read().split("\n")
    keep = []
    for line in text:
        if line.strip() == MARKER:
            break
        keep.append(line)
    while keep and keep[-1] == "":
        keep.pop()
    return keep


def hand_items(lines):
    """Positions of the hand-placed dressing and the hand parcels' polygons (so the generated parts avoid them)."""
    items, polys = [], []
    for line in lines or []:
        t = line.strip().split()
        if not t:
            continue
        for f in t:
            if f.startswith("at="):
                v = [float(a) for a in f[3:].split(",")]
                items.append((t[0], v[0], v[1]))
            if f.startswith("poly=") and t[0] == "parcel":
                polys.append([tuple(float(a) for a in q.split(",")) for q in f[5:].split(";")])
    return items, polys


