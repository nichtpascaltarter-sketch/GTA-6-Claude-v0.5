def poly_text(poly):
    return ";".join("%s,%s" % (fmt(x), fmt(y)) for x, y in poly)


def write_block(bid, title, parcels, items, hand):
    lines = []
    if hand:
        lines += hand
    else:
        lines.append("ntw 1 block id=cl.%s district=cl" % bid)
        lines.append("# %s" % title)
    lines.append(MARKER)
    corners = {q for p in parcels for q in p["poly"]}
    pn = 1
    if hand:
        while any(("cl.%s.p%02d" % (bid, pn)) in l for l in hand):
            pn += 1
    for p in parcels:
        pid = "cl.%s.p%02d" % (bid, pn)
        pn += 1
        e, side = p["front"]["edge"], p["front"]["side"]
        ground, paint = p["ground"], p["paint"]
        grade, rng_ = grade_of(p["poly"], e["name"])
        p["grade"], p["sidewalks"], p["id"] = grade, rng_, pid
        poly = p["poly"] if grade is None else run_under(with_tees(p["poly"], corners), grade + 0.03)
        lines.append("parcel %s poly=%s use=%s ground=%s front=%s:%s%s" % (pid, poly_text(poly), p["use"], ground, e["id"], "left" if side > 0 else "right",
                                                                           "" if grade is None else " grade=%.2f" % grade))
        for kind, poly in paint:
            lines.append("  paint kind=%s poly=%s" % (kind, poly_text(poly)))
        lines.append("end")
    for kind, piece, x, y, yaw, extra in items:
        f = "%s kind=%s at=%s,%s" % (kind, piece, fmt(x), fmt(y))
        if "z" in extra:
            f += ",%s" % fmt(extra["z"])
        if kind == "tree":
            f += " h=%s" % fmt(extra["h"])
        if kind == "plant":
            f += " scale=%s" % fmt(extra["scale"])
        if yaw is not None:
            f += " yaw=%s" % fmt(yaw, 1)
        lines.append(f)
    path = os.path.join(WORLD, "districts/cl/blocks", bid, "block.ntw")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w").write("\n".join(lines) + "\n")
    return path


