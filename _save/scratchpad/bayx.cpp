int main() {
    Jobs::init(2);
    WorldMap map; map.generate();
    float prev = 0;
    for (float y = -2000.f; y <= 4000.f; y += 25.f) {
        float xs = 3000.f;
        for (float x = 3000.f; x < 4600.f; x += 10.f) { if (map.isWater(x, y)) { xs = x; break; } xs = x; }
        if (fabsf(xs - prev) > 30.f) printf("y %.0f xs %.0f (prev %.0f)\n", y, xs, prev);
        prev = xs;
    }
    fflush(stdout);
    Jobs::shutdown();
}
