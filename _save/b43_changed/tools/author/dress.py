def hw_on(e, side):
    """The kerb line on one side: side +1 left of travel, -1 right (edge_side_dist's)."""
    return e["hwL"] if side > 0 else e["hwR"]


def sw_on(e, side):
    """The sidewalk on one side (as hw_on)."""
    return e["swL"] if side > 0 else e["swR"]


