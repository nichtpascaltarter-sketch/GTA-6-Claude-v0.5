def flood(seeds, blocked=None):
    """The free cells connected to the seeds (scanline fill); blocked: the cells that aren't free (taken, without it)."""
    tk = taken if blocked is None else blocked
    region = np.zeros((NY, NX), bool)
    stack = []
    for sx, sy in seeds:
        i, j = int((sx - X0) / MPP), int((sy - Y0) / MPP)
        if tk[j, i]:
            raise SystemExit("dress.py: seed %.1f,%.1f is on a street or in the water" % (sx, sy))
        stack.append((i, j))
    while stack:
        i, j = stack.pop()
        if region[j, i] or tk[j, i]:
            continue
        a = i
        while a > 0 and not tk[j, a - 1] and not region[j, a - 1]:
            a -= 1
        b = i
        while b < NX - 1 and not tk[j, b + 1] and not region[j, b + 1]:
            b += 1
        region[j, a:b + 1] = True
        for jj in (j - 1, j + 1):
            if 0 <= jj < NY:
                row = ~tk[jj, a:b + 1] & ~region[jj, a:b + 1]
                k = 0
                while k <= b - a:
                    if row[k]:
                        stack.append((a + k, jj))
                        while k <= b - a and row[k]:
                            k += 1
                    k += 1
    return region


def outline(region):
    """The region's outline as a simplified polygon (CCW), by rays from its centroid (the blocks are star-shaped)."""
    jj, ii = np.nonzero(region)
    cx, cy = X0 + (ii.mean() + 0.5) * MPP, Y0 + (jj.mean() + 0.5) * MPP
    pts = []
    for k in range(720):
        a = k * math.pi / 360
        dx, dy = math.cos(a), math.sin(a)
        last = (cx, cy)
        r = 0.0
        while True:
            r += MPP * 0.5
            x, y = cx + dx * r, cy + dy * r
            i, j = int((x - X0) / MPP), int((y - Y0) / MPP)
            if not (0 <= i < NX and 0 <= j < NY) or not region[j, i]:
                break
            last = (x, y)
        pts.append(last)
    return rdp_closed(pts, 0.45)


def rdp(pts, eps):
    if len(pts) < 3:
        return pts
    (ax, ay), (bx, by) = pts[0], pts[-1]
    L = math.hypot(bx - ax, by - ay) or 1e-9
    dmax, imax = 0.0, 0
    for k in range(1, len(pts) - 1):
        d = abs((bx - ax) * (ay - pts[k][1]) - (ax - pts[k][0]) * (by - ay)) / L
        if d > dmax:
            dmax, imax = d, k
    if dmax <= eps:
        return [pts[0], pts[-1]]
    return rdp(pts[:imax + 1], eps)[:-1] + rdp(pts[imax:], eps)


def rdp_closed(pts, eps):
    # split at the two points farthest apart, simplify both halves
    n = len(pts)
    far = max(range(n), key=lambda k: (pts[k][0] - pts[0][0]) ** 2 + (pts[k][1] - pts[0][1]) ** 2)
    a = rdp(pts[0:far + 1], eps)
    b = rdp(pts[far:] + [pts[0]], eps)
    poly = a[:-1] + b[:-1]
    return poly


def area(poly):
    return 0.5 * sum(poly[k][0] * poly[(k + 1) % len(poly)][1] - poly[(k + 1) % len(poly)][0] * poly[k][1] for k in range(len(poly)))


def clip(poly, nx, ny, c):
    """Sutherland-Hodgman: the part of poly where nx*x + ny*y <= c."""
    out = []
    n = len(poly)
    for k in range(n):
        p, q = poly[k], poly[(k + 1) % n]
        dp, dq = nx * p[0] + ny * p[1] - c, nx * q[0] + ny * q[1] - c
        if dp <= 0:
            out.append(p)
        if (dp < 0 < dq) or (dq < 0 < dp):
            f = dp / (dp - dq)
            out.append((p[0] + (q[0] - p[0]) * f, p[1] + (q[1] - p[1]) * f))
    return out


def dedupe(poly):
    """Drop repeated points (to the centimetre) and collinear ones."""
    out = []
    for q in poly:
        q = (round(q[0], 2), round(q[1], 2))
        if not out or q != out[-1]:
            out.append(q)
    while len(out) > 1 and out[0] == out[-1]:
        out.pop()
    k = 0
    while len(out) > 3 and k < len(out):
        a, b, c = out[k - 1], out[k], out[(k + 1) % len(out)]
        if abs((b[0] - a[0]) * (c[1] - a[1]) - (b[1] - a[1]) * (c[0] - a[0])) < 0.02:
            out.pop(k)
        else:
            k += 1
    return out


def inside(poly, x, y):
    c = False
    n = len(poly)
    for k in range(n):
        (ax, ay), (bx, by) = poly[k], poly[(k + 1) % n]
        if (ay > y) != (by > y) and x < (bx - ax) * (y - ay) / (by - ay) + ax:
            c = not c
    return c


