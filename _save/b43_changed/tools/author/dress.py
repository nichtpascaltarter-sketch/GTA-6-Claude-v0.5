def dress_sidewalks(bid, polys, rng, avoid):
    """Street trees, lights, hydrants, bins, benches and news boxes on the sidewalks along a block's frontages."""
    out = []
    placed = list(avoid)   # (kind, x, y)

    def free(x, y, r, kinds=None):
        for k, px, py in placed:
            if (kinds is None or k in kinds) and (px - x) ** 2 + (py - y) ** 2 < r * r:
                return False
        return True

    seen = set()
    for poly in polys:
        for fid, f in frontages(poly).items():
            if fid in seen:
                continue
            seen.add(fid)
            e = f["edge"]
            side = f["side"]   # +1: the block is left of travel
            hw, sw = hw_on(e, side), sw_on(e, side)
            if sw < 2.0:
                continue
            shop = e["name"] in SHOP_STREETS
            big = e["cls"] in (RC_AVENUE, RC_BOULEVARD)
            s0, s1 = e["cut0"] + 5.0, e["plen"] - e["cut1"] - 5.0
            if s1 - s0 < 8.0:
                continue

            def spot(s, off):
                (px, py), (tx_, ty_) = at(e, s)
                lx, ly = -ty_ * side, tx_ * side   # toward the block
                return px + lx * off, py + ly * off, (lx, ly)

            # (only the stretch along this block: the part of the sidewalk whose building side touches the polygon)
            def ours(s):
                x, y, (lx, ly) = spot(s, hw + sw + 1.0)
                return any(inside(p, x, y) for p in polys)

            # street lights: avenues and boulevards every 30 m, streets every 34 m; the arm over the road
            step = 30.0 if big else 34.0
            phase = rng.uniform(0.3, 0.7) * step
            s = s0 + phase * 0.5
            while s <= s1:
                if ours(s):
                    x, y, (lx, ly) = spot(s, hw + 0.7)
                    if free(x, y, 8.0, {"light"}) and free(x, y, 2.0):
                        out.append(("light", "lib.light.street_cobra", x, y, yaw_toward(-lx, -ly), {}))
                        placed.append(("light", x, y))
                s += step
            # street trees between the lights, on sidewalks of 3.5 m or more
            if sw >= 3.5:
                tree, h0, h1 = TREES.get(e["name"], DEFAULT_TREE)
                tstep = 15.0 if shop else 17.0
                s = s0 + rng.uniform(2.0, 6.0)
                while s <= s1:
                    if ours(s):
                        x, y, _ = spot(s, hw + 1.2)
                        if free(x, y, 4.0) and free(x, y, 6.0, {"light"}):
                            out.append(("tree", tree, x, y, None, {"h": rng.uniform(h0, h1)}))
                            placed.append(("tree", x, y))
                    s += tstep
            # a hydrant near one end of each stretch
            for s in (s0 + 1.0, s1 - 1.0):
                if ours(s):
                    x, y, (lx, ly) = spot(s, hw + 0.6)
                    if free(x, y, 30.0, {"prop.hydrant"}) and free(x, y, 2.0):
                        out.append(("prop", "lib.prop.hydrant", x, y, None, {}))
                        placed.append(("prop.hydrant", x, y))
                        break
            # shopping streets: bins at both ends, a bench and a news box at the building side, parking meters
            if shop or big:
                for s in (s0 + 3.0, s1 - 3.0):
                    if ours(s):
                        x, y, (lx, ly) = spot(s, hw + 0.9)
                        if free(x, y, 2.5):
                            out.append(("prop", "lib.prop.trash_bin", x, y, None, {}))
                            placed.append(("prop.bin", x, y))
                sm = (s0 + s1) / 2
                if ours(sm):
                    x, y, (lx, ly) = spot(sm, hw + sw - 0.7)
                    if free(x, y, 3.0):
                        out.append(("prop", "lib.prop.bench", x, y, yaw_toward(-lx, -ly), {}))
                        placed.append(("prop.bench", x, y))
            if shop:
                if ours(s0 + 6.0):
                    x, y, (lx, ly) = spot(s0 + 6.0, hw + sw - 0.6)
                    if free(x, y, 2.0):
                        out.append(("prop", "lib.prop.news_box", x, y, yaw_toward(-lx, -ly), {}))
                        placed.append(("prop.news", x, y))
                s = s0 + 9.0
                while s <= s1 - 6.0:
                    if ours(s):
                        x, y, (lx, ly) = spot(s, hw + 0.45)
                        if free(x, y, 2.5):
                            out.append(("prop", "lib.prop.parking_meter", x, y, yaw_toward(lx, ly), {}))
                            placed.append(("prop.meter", x, y))
                    s += 14.0
    return out


# ------------------------------------------------------------------------------------- the dead ends' turning paths
# The game turns a dead end's traffic round the node (src/game/lanes.cpp, the dead end's connectors). From each
# lane's end, 9 m short of the node (0.3 of a shorter street), it swings out to a circle round the node: the lane's
# offset plus 3.4 m, 4.8 to 6.5 m, and 2.2 m inside a written bulb. It turns half round it and comes back into the lane
# out. It keeps that path 4.2 m clear of the props' colliders, or else pulls the circle back toward the street, 1.5 m a
# try, for nine tries. When no try is clear it gives the dead end up, and routing avoids it. So no prop with a collider
# stands within 4.2 m of any of the nine paths (with a margin for the game's smoothed lanes).
LANE_W = {RC_BOULEVARD: 3.4, RC_AVENUE: 3.3, RC_STREET: 3.2, RC_LANE: 3.0}   # (roadnet.cpp's, as roads.ntw writes no
MEDIAN = {RC_BOULEVARD: 4.0}                                                 #  lane widths or medians)
UTURN_CLEAR, UTURN_MARGIN = 4.2, 0.1


def bezier(p0, p1, p2, p3):
    """lanes.cpp's sampleBezier: one point about every metre of the control polygon, 6 to 48 steps."""
    n = max(6, min(48, int(math.dist(p0, p1) + math.dist(p1, p2) + math.dist(p2, p3))))
    return [tuple(p0[j] * (1 - t) ** 3 + p1[j] * 3 * (1 - t) ** 2 * t + p2[j] * 3 * (1 - t) * t * t + p3[j] * t ** 3 for j in (0, 1))
            for t in (i / n for i in range(n + 1))]


def turning_paths():
    """Per dead end: the box of its turning paths and their points, every lane's, at all nine tries."""
    out = []
    for e in edges:
        for end, ni in ((0, e["n0"]), (1, e["n1"])):
            n = nodes[ni]
            if n["degree"] != 1 or e["lanesF"] == 0 or e["lanesB"] == 0 or e["n0"] == e["n1"]:
                continue
            W, half = LANE_W.get(e["cls"], 3.2), MEDIAN.get(e["cls"], 0.0) / 2
            cut = min(9.0, e["length"] * 0.3)
            (cx, cy), (tx, ty) = at(e, e["plen"] - cut if end == 1 else cut)
            dx, dy = (tx, ty) if end == 1 else (-tx, -ty)   # (toward the dead end)
            rx, ry = dy, -dx                                  # (to its right)
            n_in, n_out = (e["lanesF"], e["lanesB"]) if end == 1 else (e["lanesB"], e["lanesF"])
            rmax = min(6.5, max(4.8, n["bulb"] - 2.2)) if n["bulb"] else 6.5
            pts = []
            for k in range(n_in):
                o_in, o_out = half + (k + 0.5) * W, half + (min(k, n_out - 1) + 0.5) * W
                R = min(rmax, max(4.8, o_in + 3.4))
                p0, p3 = (cx + rx * o_in, cy + ry * o_in), (cx - rx * o_out, cy - ry * o_out)
                for a in range(9):
                    ox, oy = n["x"] - dx * 1.5 * a, n["y"] - dy * 1.5 * a
                    b1, b2 = (ox + rx * R, oy + ry * R), (ox - rx * R, oy - ry * R)
                    k1 = max(((b1[0] - p0[0]) * dx + (b1[1] - p0[1]) * dy) * 0.45, 1.0)
                    k2 = max(((b2[0] - p3[0]) * dx + (b2[1] - p3[1]) * dy) * 0.45, 1.0)
                    pts += bezier(p0, (p0[0] + dx * k1, p0[1] + dy * k1), (b1[0] - dx * k1, b1[1] - dy * k1), b1)
                    pts += [(ox + (dx * math.cos(th) - rx * math.sin(th)) * R, oy + (dy * math.cos(th) - ry * math.sin(th)) * R)
                            for th in (-math.pi / 2 + math.pi * s / 12 for s in range(1, 13))]
                    pts += bezier(b2, (b2[0] - dx * k2, b2[1] - dy * k2), (p3[0] + dx * k2, p3[1] + dy * k2), p3)
            if pts:
                out.append(((min(p[0] for p in pts), min(p[1] for p in pts), max(p[0] for p in pts), max(p[1] for p in pts)), pts))
    return out


TURNING = turning_paths()
COLLIDERS = {}   # piece: (its collider's reach in plan: a cylinder's radius, a box's half diagonal; its height) or None
LEFT_OUT = []    # (block, piece, x, y)


def collider_of(piece):
    if piece not in COLLIDERS:
        COLLIDERS[piece] = None
        for t, rid, kv in ntw_records(os.path.join(WORLD, "lib", "catalog.ntw")):
            if t == "piece" and rid == piece and kv.get("collide", "none") != "none":
                w, d, _ = (float(v) for v in kv.get("body", kv["size"]).split("x"))
                COLLIDERS[piece] = (math.hypot(w, d) / 2 if kv["collide"] == "box" else max(w, d) / 2, float(kv["size"].split("x")[2]))
    return COLLIDERS[piece]


def clear_turning_paths(bid, items):
    """The items less the props whose colliders come within the game's reach of a dead end's turning paths."""
    kept = []
    for it in items:
        kind, piece, x, y, yaw, extra = it
        c = collider_of(piece)
        if c is not None:
            reach = c[0] * (extra["h"] / c[1] if "h" in extra else extra.get("scale", 1.0)) + UTURN_CLEAR + UTURN_MARGIN
            if any(x0 - reach <= x <= x1 + reach and y0 - reach <= y <= y1 + reach and any(math.hypot(q[0] - x, q[1] - y) <= reach for q in pts)
                   for (x0, y0, x1, y1), pts in TURNING):
                LEFT_OUT.append((bid, piece, x, y))
                continue
        kept.append(it)
    return kept


def dress_parcel(p, rng, yards=True):
    """A parcel's ground and paint, and its yard's trees and shrubs (not without yards: the south bank's, until their
    buildings)."""
    recs = []
    poly = p["poly"]
    ux, uy = p["u"]
    vx, vy = p["v"]   # into the parcel from its street
    us = [q[0] * ux + q[1] * uy for q in poly]
    vs = [q[0] * vx + q[1] * vy for q in poly]
    u0, u1, v0, v1 = min(us), max(us), min(vs), max(vs)

    def xy(u, v):   # (u along the street, v away from it) to plan x, y
        return (u * ux + v * vx, u * uy + v * vy)

    if p["use"] == "residential":
        paint = []
        # a driveway on one side, 3 m wide and 9 m deep
        side = rng.random() < 0.5
        da, db = (u0 + 0.8, u0 + 3.8) if side else (u1 - 3.8, u1 - 0.8)
        if u1 - u0 > 9.0 and v1 - v0 > 12.0:
            paint.append(("paving", [xy(da, v0), xy(db, v0), xy(db, v0 + 9.0), xy(da, v0 + 9.0)]))
        recs.append(("parcel_ground", "lawn", paint))
        if not yards:
            return recs
        # a tree or two in the back yard, shrubs by the front
        for k in range(rng.choice((1, 1, 2))):
            u = rng.uniform(u0 + 3.0, u1 - 3.0)
            v = rng.uniform(v0 + (v1 - v0) * 0.7, v1 - 3.0)
            kind = rng.choice(("lib.veg.live_oak", "lib.veg.palm", "lib.veg.live_oak", "lib.veg.street_tree"))
            h = {"lib.veg.live_oak": (6.0, 8.5), "lib.veg.palm": (6.5, 8.5), "lib.veg.street_tree": (5.0, 6.5)}[kind]
            x, y = xy(u, v)
            recs.append(("tree", kind, x, y, None, {"h": rng.uniform(*h)}))
        for k in range(rng.choice((1, 2, 2, 3))):
            u = rng.uniform(u0 + 1.5, u1 - 1.5)
            if da - 1.0 < u < db + 1.0:
                continue
            x, y = xy(u, v0 + rng.uniform(1.2, 2.5))
            recs.append(("plant", "lib.veg.shrub", x, y, None, {"scale": rng.uniform(0.8, 1.2), "lot": p}))
    else:
        recs.append(("parcel_ground", "paving", []))
    return recs


# ------------------------------------------------------------------------------------- the yard shrubs, by the buildings
# A lot's shrubs are drawn by its front (dress_parcel) without its building, which street.py places later, so the
# buildings' files place them: a shrub a footprint covers becomes a foundation planting along the facade where CLEAR or
# more lies between the sidewalk's back edge and the front wall, else a planting in the nearer side yard with CLEAR or
# more clear (else the farther one), else it goes. None stands on a door's way: DOOR_CLEAR kept clear in front of every
# entrance and along its walk to the sidewalk (a back door's by the driveway's side yard, else the nearer one), nor on
# the driveway. A shrub's reach is the catalog's: lib.veg.shrub's size= (its foliage at its widest, any way it turns)
# times its scale. One shrinks to fit its place, but not under MIN_SCALE: else it goes. A shrub no footprint or way
# reaches stays where it was drawn. A re-run after any building change re-places them.
CLEAR = 0.8         # (the least clear width that takes a planting)
MIN_SCALE = 0.25    # (the least a shrub shrinks to fit: worldc takes no plant under 0.2)
MARGIN = 0.05       # (m: a shrub's reach keeps this far off the walls, the ways and its lot's edge)
DOOR_CLEAR = 1.2    # (the way kept clear in front of a door and along its walk)
PLANS, LAYOUTS = {}, {}


def catalog_size(piece):
    """A piece's size= in the library's catalog (world/lib/catalog.ntw): (W, D, H) at scale 1."""
    for raw in open(os.path.join(WORLD, "lib", "catalog.ntw"), encoding="utf-8"):
        t = raw.split("#")[0].split()
        if len(t) > 2 and t[0] == "piece" and t[1] == piece:
            for kv in t[2:]:
                if kv.startswith("size="):
                    return tuple(float(v) for v in kv[5:].split("x"))
    raise SystemExit("dress.py: the catalog gives %s no size=" % piece)


SHRUB_W = max(catalog_size("lib.veg.shrub")[:2])   # (a shrub's reach across at scale 1)
