# file's hand-written part, everything above the GENERATED marker, as it is: Domino Park (b010) is hand-made. Its output
# is data: run it once per design change, then format the files (ntwfmt) and review the check image and in-game shots.
# Positions are plan x,y; worldc puts every height on the graded ground or the sidewalk.
# No prop with a collider stands where the game turns a dead end's traffic round (see clear_turning_paths).
