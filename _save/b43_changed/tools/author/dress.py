# 2), as an authoring script (section 5.3). It reads the district's streets as the game builds them (worlddump's print
# of world.bin's roads), finds the blocks between them, cuts each into parcels along its frontages, levels each parcel a
# kerb's step under its sidewalks, and dresses the sidewalks (street trees, street lights, hydrants, bins, benches, news
# boxes), the yards and the riverfronts; and the park edge north of Calle Nueve (b026). The south bank's blocks (b028
